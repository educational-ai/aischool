export function articleForLesson(lesson: Lesson) {
  const article = articleById.get(lesson.id);
  if (!article) {
    throw new Error(`Missing authored article for lesson ${lesson.id}`);
  }
  return article;
}

export function articleIsAuthored(id: string) {
  return articleById.has(id);
}

export function articleConnections(id: string) {
  const source = articleById.get(id) ?? "";
  const outgoing = [...source.matchAll(/\]\(\/lesson\/(\d{2})(?:#[^)]+)?\)/g)]
    .map((match) => match[1])
    .filter((target, index, all) => target !== id && all.indexOf(target) === index);
  const incoming = [...articleById.entries()]
    .filter(([sourceId, markdown]) => {
      if (sourceId === id) return false;
      return new RegExp(`\\]\\(/lesson/${id}(?:#[^)]+)?\\)`).test(markdown);
    })
    .map(([sourceId]) => sourceId);
  return { outgoing, incoming };
}
